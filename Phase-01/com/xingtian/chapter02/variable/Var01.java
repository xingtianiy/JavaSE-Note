public class Var01 {
    public static void main(String[] args) {
        // 变量有三个基本要素(类型 + 名称 + 值)
        int a = 1; // 定义了一个变量,数据类型:int(整型),变量名:a,数据值:1
        int b = 3; // 定义了一个变量,数据类型:int(整型),变量名:b,数据值:3
        b = 89;    // 把值 89 赋给变量 b
        System.out.println(a); // 输出变量 a 的值
        System.out.println(b); // 输出变量 b 的值
    }
}
