public class Var02 {
    public static void main(String[] args) {
        // 1.基础用法
        // 定义变量,再进行输出
        int a = 10;
        System.out.println(a); // 10
        System.out.println(a); // 10
        System.out.println(a); // 10

        // 2.变量参与计算
        int b = 30;
        int c = 20;
        System.out.println(b + c); // 50

        // 3.修改变量记录的值
        a = 50;
        System.out.println(a); // 50
    }
}
