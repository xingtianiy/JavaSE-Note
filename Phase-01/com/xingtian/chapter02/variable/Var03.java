public class Var03 {
    public static void main(String[] args) {
        // 注意事项
        // 在一条语句中，可以定义多个变量
        int d = 100, e = 200, f = 300;
        System.out.println(d);
        System.out.println(e);
        System.out.println(f);

        // 变量在使用之前一定要进行赋值
        // int g;
        // g = 500;
        // 建议: 以后在定义变量的时候,请直接复制,不要把赋值分开写.
        // System.out.println(g);
    }
}
