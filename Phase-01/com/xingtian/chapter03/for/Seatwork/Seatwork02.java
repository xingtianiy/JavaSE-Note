public class Seatwork02 {
	public static void main(String[] args) {
		// 执行任务
		// 实现循环执行任务，需要选择循环实现
		// 任务是打印输出，只需要5次，3次自动完成任务
		// 注意任务执行的循环次数和任务内容

		// 执行任务
		// 1.因为任务需要重复执行某未完成的步骤，所以需要循环
		// 循环次数为5次
		// 开始循环次数为1
		// 结束循环次数为5
		for (int i = 1; i <= 5; i++) {
			System.out.println("执行任务的第" + i + "次");
		}
	}
}